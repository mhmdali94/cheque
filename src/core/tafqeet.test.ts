describe('باقي الصيغ', () => {
  it('فقط وقدره بدون صفة', () => {
    const options = resolveTafqeetOptions('qadruhu');
    expect(tafqeet(5, options)).toBe('فقط وقدره خمسة جنيهات لا غير');
    expect(tafqeet(1, options)).toBe('فقط وقدره جنيه واحد لا غير');
    expect(tafqeet(2, options)).toBe('فقط وقدره جنيهان لا غير');
  });

  it('مبلغ فقط', () => {
    expect(tafqeet(500, resolveTafqeetOptions('mablagh'))).toBe('مبلغ خمسمائة جنيه مصري فقط لا غير');
  });

  it('صيغة مخصصة بمتغير العملة تطبق مطابقة العدد', () => {
    const options = resolveTafqeetOptions(CUSTOM_PRESET_ID, 'المبلغ {المبلغ} {العملة} فقط');
    expect(tafqeet(7, options)).toBe('المبلغ سبعة جنيهات مصرية فقط');
  });

  it('صيغة مخصصة بوحدة مكتوبة تتطبع زي ما هي', () => {
    const options = resolveTafqeetOptions(CUSTOM_PRESET_ID, 'فقط {المبلغ} جنيه لا غير');
    expect(tafqeet(1, options)).toBe('فقط واحد جنيه لا غير');
    expect(tafqeet(3, options)).toBe('فقط ثلاثة جنيه لا غير');
  });
});

describe('العدد بالحروف والحدود', () => {
  it('المراتب والعطف', () => {
    expect(numberToWords(1001)).toBe('ألف وواحد');
    expect(numberToWords(10000)).toBe('عشرة آلاف');
    expect(numberToWords(103000)).toBe('مائة وثلاثة آلاف');
    expect(numberToWords(3000000)).toBe('ثلاثة ملايين');
    expect(numberToWords(2000000000)).toBe('ملياران');
    expect(numberToWords(1000001)).toBe('مليون وواحد');
  });

  it.each([0, -1, 1.5, 1_000_000_000_000])('يرفض %d', (value) => {
    expect(() => tafqeet(value)).toThrow(RangeError);
  });
});

describe('بالقروش', () => {
  it.each([
    [148500, 45, 'فقط مائة وثمانية وأربعون ألف وخمسمائة جنيه مصري وخمسة وأربعون قرش لا غير'],
    [3990213, 45, 'فقط ثلاثة ملايين وتسعمائة وتسعون ألف ومائتان وثلاثة عشر جنيه مصري وخمسة وأربعون قرش لا غير'],
    [0, 50, 'فقط خمسون قرش لا غير'],
    [1, 1, 'فقط جنيه مصري واحد وقرش واحد لا غير'],
    [3, 2, 'فقط ثلاثة جنيهات مصرية وقرشان لا غير'],
    [10, 5, 'فقط عشرة جنيهات مصرية وخمسة قروش لا غير'],
    [2500000, 75, 'فقط مليونان وخمسمائة ألف جنيه مصري وخمسة وسبعون قرش لا غير'],
    [999999999999, 99, 'فقط تسعمائة وتسعة وتسعون مليار وتسعمائة وتسعة وتسعون مليون وتسعمائة وتسعة وتسعون ألف وتسعمائة وتسعة وتسعون جنيه مصري وتسعة وتسعون قرش لا غير'],
  ])('%d جنيه و%d قرش', (value, piasters, expected) => {
    expect(tafqeet(value, accounting, piasters)).toBe(expected);
  });

  it('الفصحى', () => {
    expect(tafqeet(5, fusha, 11)).toBe('فقط خمسة جنيهات مصرية وأحد عشر قرشاً لا غير');
  });

  it('صيغة «مبلغ فقط» القروش قبل «فقط لا غير»', () => {
    expect(tafqeet(500, resolveTafqeetOptions('mablagh'), 25)).toBe('مبلغ خمسمائة جنيه مصري وخمسة وعشرون قرش فقط لا غير');
  });

  it('صيغة مخصصة بوحدة مكتوبة: القروش قبل «لا غير»', () => {
    const options = resolveTafqeetOptions(CUSTOM_PRESET_ID, 'فقط {المبلغ} جنيه لا غير');
    expect(tafqeet(7, options, 25)).toBe('فقط سبعة جنيه وخمسة وعشرون قرش لا غير');
  });

  it('صيغة مخصصة بمكان القروش', () => {
    const options = resolveTafqeetOptions(CUSTOM_PRESET_ID, 'فقط {المبلغ} {العملة} و{القروش} لا غير'.replace('و{القروش}', '{القروش}'));
    expect(tafqeet(7, options, 25)).toBe('فقط سبعة جنيهات مصرية وخمسة وعشرون قرش لا غير');
  });

  it('من غير قروش زي ما كان بالظبط', () => {
    expect(tafqeet(148500, accounting, 0)).toBe('فقط مائة وثمانية وأربعون ألف وخمسمائة جنيه مصري لا غير');
  });

  it.each([-1, 100, 1.5])('قروش غلط %d', (piasters) => {
    expect(() => tafqeet(5, accounting, piasters)).toThrow(RangeError);
  });
});
